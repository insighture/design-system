/**
 * Build the repo as an AI skill. The repo root is the skill: SKILL.md routes
 * to references/*.md, which point at brand/, templates/ and docs/.
 *
 *   npm run skill
 *
 * Hand-written: SKILL.md, references/*.md (except components.md), docs/*.md,
 * scripts/check_brand.py. Generated here, and committed:
 *   brand/tokens.css      the token set, from src/styles/
 *   brand/palette.json    every allowed hex + logo hashes, for check_brand.py
 *   references/components.md   index of docs/<Component>.md
 *   GUIDELINES.md         SKILL.md's references as one document, for people
 *   AGENTS.md             SKILL.md + every reference inline, for tools that
 *                         read one file (Codex, Cursor, Copilot, Gemini CLI,
 *                         Custom GPTs, Gems)
 * Then it zips the files that ship (everything not export-ignore'd in
 * .gitattributes) to dist/insighture-design-system.zip and checks the zip
 * against Tracelet's upload rules, failing rather than writing one Tracelet
 * would refuse. Rebuild after changing any of the hand-written files, the
 * logo, templates or tokens (run `npm run templates` first if the templates
 * changed).
 */
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleFiles, checkFiles, checkZip, report } from './tracelet-check.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const name = 'insighture-design-system';
const read = (f) => fs.readFile(path.join(root, f), 'utf8');
const write = (f, s) => fs.writeFile(path.join(root, f), s);

// Reference order, as numbered in GUIDELINES.md. Section 5 groups the media.
const SECTIONS = [
  { file: 'look-and-voice.md' },
  { file: 'colour.md' },
  { file: 'typography.md' },
  { file: 'layout.md' },
  {
    title: 'Applying it, by medium',
    intro:
      'Start from the ready-made files in [`templates/`](templates/README.md) (PowerPoint, Word,\nPDF, email and social) rather than a blank document.',
    media: ['documents.md', 'slides.md', 'web.md', 'spreadsheets.md', 'charts.md', 'email-social.md'],
  },
  { file: 'logo.md' },
  { file: 'checklist.md' },
];
const ALL_REFS = SECTIONS.flatMap((s) => s.media ?? [s.file]).concat('components.md');

const GENERATED = '<!-- Generated by `npm run skill` in github.com/insighture/design-system. Do not edit; edit SKILL.md or references/ instead. -->';
const stripClaudeOnly = (s) => s.replace(/<!-- claude-only -->[\s\S]*?<!-- \/claude-only -->\n*/g, '');
const stripFrontmatter = (s) => s.replace(/^---\n[\s\S]*?\n---\n+/, '');

/** Shift every markdown heading (outside code fences) down by `by` levels. */
function shiftHeadings(md, by, firstPrefix = '') {
  let fenced = false;
  let first = true;
  return md
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) fenced = !fenced;
      const m = !fenced && line.match(/^(#{1,6})\s+(.*)$/);
      if (!m) return line;
      const text = first && firstPrefix ? `${firstPrefix}${m[2]}` : m[2];
      first = false;
      return `${'#'.repeat(Math.min(6, m[1].length + by))} ${text}`;
    })
    .join('\n');
}

// 1. brand/tokens.css and brand/palette.json from the design tokens.
const tokens = await Promise.all(['src/styles/tokens.css', 'src/styles/semantic.css'].map(read));
await write('brand/tokens.css', tokens.join('\n'));

// Every hex in the tokens is allowed, named by the first token that defines
// it; the rest (gradient stops) are named after the token they appear in.
const colours = {};
for (const pass of ['define', 'other']) {
  for (const line of tokens[0].split('\n')) {
    const token = line.match(/--ins-([\w-]+)\s*:\s*(#?)/);
    if (pass === 'define' ? !token?.[2] : !token) continue;
    for (const [, hex] of line.matchAll(/#([0-9a-f]{6})\b/gi)) colours[hex.toUpperCase()] ??= token[1];
  }
}
colours.FFFFFF ??= 'pure white (print)';
const logoFiles = [
  ...(await fs.readdir(path.join(root, 'brand/logo'))).filter((f) => f.endsWith('.svg')).map((f) => `brand/logo/${f}`),
  ...['logo-black.png', 'logo-white.png', 'logo-white-mono.png'].map((f) => `templates/assets/${f}`),
].sort();
const logoHashes = await Promise.all(
  logoFiles.map(async (f) => crypto.createHash('sha256').update(await fs.readFile(path.join(root, f))).digest('hex')),
);
await write('brand/palette.json', JSON.stringify({ colours, logoHashes }, null, 2) + '\n');

// 2. references/components.md: one row per docs/<Component>.md.
const components = [];
for (const f of (await fs.readdir(path.join(root, 'docs'))).filter((f) => f.endsWith('.md')).sort()) {
  const md = await read(`docs/${f}`);
  const category = md.match(/^---\n[\s\S]*?^category:\s*(.+)$/m)?.[1].trim() ?? 'Other';
  const body = stripFrontmatter(md);
  const title = body.match(/^#\s+(.+)$/m)?.[1].trim() ?? f.replace(/\.md$/, '');
  const summary = body.split('\n').find((l) => l.trim() && !l.startsWith('#'))?.trim() ?? '';
  components.push({ category, title, file: `docs/${f}`, summary });
}
components.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));
await write(
  'references/components.md',
  `${GENERATED}

# React components

\`@insighture/design-system\` ships these components. Wrap the app in
\`<InsightureProvider defaultTheme="light">\` and import
\`@insighture/design-system/styles.css\` first (\`references/web.md\`). Read a
component's file for its props, variants and guidance before using it.

| Component | Category | File | What it is |
| --- | --- | --- | --- |
${components.map((c) => `| ${c.title} | ${c.category} | \`${c.file}\` | ${c.summary.replace(/\|/g, '\\|')} |`).join('\n')}
`,
);

// 3. GUIDELINES.md: the references as one numbered document, for people.
const refs = Object.fromEntries(await Promise.all(ALL_REFS.map(async (f) => [f, stripClaudeOnly(await read(`references/${f}`))])));
const repoLinks = (s) => s.replace(/(\]\(|src=")\.\.\//g, '$1');
const guidelines = [
  `${GENERATED}

# Insighture brand guidelines

One visual system for **everything**: Word documents, PDFs, slide decks,
spreadsheets, websites, email, social posts, diagrams and charts. The React
package in this repo is just one way to apply it. The rules below work in any
medium. AI assistants get the same rules through [\`SKILL.md\`](SKILL.md).`,
];
SECTIONS.forEach((s, i) => {
  const n = `${i + 1}. `;
  if (s.media) {
    guidelines.push(`## ${n}${s.title}\n\n${s.intro}`);
    for (const f of s.media) guidelines.push(shiftHeadings(repoLinks(refs[f]).trim(), 2));
  } else {
    guidelines.push(shiftHeadings(repoLinks(refs[s.file]).trim(), 1, n));
  }
});
await write('GUIDELINES.md', guidelines.join('\n\n---\n\n') + '\n');

// 4. AGENTS.md: SKILL.md plus every reference inline, for one-file tools.
const skill = await read('SKILL.md');
const agents = [
  `${GENERATED}\n<!-- Instructions for AI assistants and coding agents: apply these rules to anything visual you make for Insighture. -->`,
  stripClaudeOnly(stripFrontmatter(skill)).trim(),
  '# Full reference\n\nThe files listed under "Read next" above, inline. Paths to templates and\nlogo files are relative to github.com/insighture/design-system.',
  ...ALL_REFS.map((f) => shiftHeadings(stripClaudeOnly(refs[f]).replace(GENERATED, '').trim(), 1)),
];
await write('AGENTS.md', agents.join('\n\n') + '\n');

// 5. The zip: every file that isn't export-ignore'd, under one top folder
// (the shape claude.ai and Tracelet both expect), checked against Tracelet.
const files = bundleFiles(root);
report('the skill bundle', await checkFiles(root, files, name));
if (process.exitCode) process.exit();

const stage = path.join(root, 'dist', '.skill-stage');
await fs.rm(stage, { recursive: true, force: true });
for (const f of files) {
  await fs.mkdir(path.dirname(path.join(stage, name, f)), { recursive: true });
  await fs.copyFile(path.join(root, f), path.join(stage, name, f));
}
const zip = path.join(root, 'dist', `${name}.zip`);
await fs.rm(zip, { force: true });
execFileSync('zip', ['-rqX', zip, name], { cwd: stage });
await fs.rm(stage, { recursive: true, force: true });
report(`dist/${name}.zip`, await checkZip(zip));
if (process.exitCode) process.exit();

console.log(`${files.length} files → ${path.relative(root, zip)}`);
